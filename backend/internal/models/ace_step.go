// ace_step.go — ACE-Step 1.5 GGUF adapter for audio.cpp.
// ACE-Step is the VOCAL model: aalap, humming, oohs, gamakas,
// Hindi/Sanskrit lyric pronunciation, and casual Indian fusion vocals.
// Memory footprint: ~9.0 GB on Apple Silicon UMA.
package models

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
)

// ACEStepAdapter runs ACE-Step 1.5 via audio.cpp GGUF.
type ACEStepAdapter struct {
	weightsDir string
}

func NewACEStepAdapter(weightsDir string) *ACEStepAdapter {
	return &ACEStepAdapter{weightsDir: weightsDir}
}

func (a *ACEStepAdapter) Info() ModelInfo {
	return ModelInfo{
		ID:          ModelACEStep,
		Name:        "ACE-Step 1.5 (GGUF)",
		MemoryGB:    9.0,
		WeightsPath: filepath.Join(a.weightsDir, "ace-step"),
		State:       StateUnloaded,
	}
}

// Generate runs ACE-Step 1.5 vocal generation via audio.cpp.
//
// ACE-Step supports several vocal modes mapped from the Nāḍ frontend:
//   - Lyrics mode: full Hindi/Sanskrit lyric synthesis
//   - Wordless mode: aalap, oohs, humming (empty --lyrics, prompt drives texture)
//   - Instrumental mode: no vocal content (fallback only)
//
// The Prompt field should contain the style descriptors generated by prompt.Builder,
// including vocal characteristics (breathiness, gamaka depth, raga name).
func (a *ACEStepAdapter) Generate(ctx context.Context, req GenerateRequest, progressCh chan<- float64) ([]byte, error) {
	weightsPath := filepath.Join(a.weightsDir, "ace-step")
	// If a direct GGUF file or subdirectory exists, locate it
	targetFile := filepath.Join(weightsPath, "ace-step-1.5-turbo-bf16.gguf")
	if _, err := os.Stat(targetFile); err == nil {
		weightsPath = targetFile
	} else if _, err := os.Stat(weightsPath); os.IsNotExist(err) {
		return nil, fmt.Errorf("ACE-Step weights not found at %s — run backend/scripts/install_ace_step.sh", weightsPath)
	}

	// audio.cpp CLI for ACE-Step 1.5
	args := []string{
		"--task", "gen",
		"--family", "ace_step",
		"--model", weightsPath,
		"--backend", "metal",
		"--task-route", "text2music",
		"--text", req.Tags,
		"--duration-seconds", fmt.Sprintf("%.0f", req.DurationSec),
		"--out", "-",
	}

	if req.Lyrics != "" {
		args = append(args, "--request-option", fmt.Sprintf("lyrics=%s", req.Lyrics))
	}

	return runAudioCpp(ctx, args, progressCh)
}
